/**
 * @module config/vocabularies
 * @description Фіксовані словники метаданих треку: жанри, настрої й тональності.
 * Адміністратор обирає значення лише з цих списків, тому кожна категорія має єдине написання
 * (без «Рок»/«рок»/«Rock»), а one-hot кодування в Recommendation Engine лишається коректним.
 * Значення мають збігатися з database/seed.sql символ у символ.
 * Розмірність вектора треку: GENRES (12) + KEYS (24) + MOODS (8) + bpm + year = 46.
 */

/** Жанри (з великої літери). */
export const GENRES = Object.freeze([
  'Електроніка',
  'Поп',
  'Інді',
  'Рок',
  'Хіп-хоп',
  'Джаз',
  'Чіл',
  'Класика',
  'Пост-панк',
  'Поп-фолк',
  'Фолк',
  'Метал',
]);

/** Настрої (з малої літери; з великої — лише при відображенні на клієнті). */
export const MOODS = Object.freeze([
  'енергійний',
  'радісний',
  'спокійний',
  'меланхолійний',
  'сумний',
  'романтичний',
  'агресивний',
  'мрійливий',
]);

/** Ноти хроматичної гами, з яких будуються тональності. */
const NOTES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];

/** Лади тональностей. */
const MODES = ['major', 'minor'];

/** 24 тональності у форматі «нота лад», напр. `"C major"`, `"F# minor"`. */
export const KEYS = Object.freeze(NOTES.flatMap((note) => MODES.map((mode) => `${note} ${mode}`)));

/** Допустимий діапазон темпу, ударів за хвилину. */
export const BPM_RANGE = Object.freeze({ min: 40, max: 250 });

/**
 * Повертає допустимий діапазон року треку: від 1 до наступного року включно
 * (нижньої межі на кшталт 1900 немає — у медіатеці є класика).
 * @param {Date} [now=new Date()] - поточна дата.
 * @returns {{min: number, max: number}} межі року.
 */
export function getYearRange(now = new Date()) {
  return { min: 1, max: now.getFullYear() + 1 };
}
